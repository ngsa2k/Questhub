def parse_zone_block(content: str, zone_id: int) -> dict:
    """Extract all coord→nodeID pairs for a given zone ID."""
    nodes = {}

    # Find the zone block: [ZONEID] = { ... }
    # We need to handle nested braces correctly
    pattern = rf'\[{zone_id}\]\s*=\s*\{{'
    match = re.search(pattern, content)
    if not match:
        return nodes

    start = match.end()
    depth = 1
    pos = start

    while pos < len(content) and depth > 0:
        ch = content[pos]
        if ch == '{':
            depth += 1
        elif ch == '}':
            depth -= 1
        pos += 1

    block = content[start:pos - 1]

    # Extract all [coord] = nodeID pairs
    for m in re.finditer(r'\[(\d+)\]\s*=\s*(\d+)', block):
        coord = int(m.group(1))
        node_id = int(m.group(2))
        nodes[coord] = node_id

    return nodes


def decode_loc(coord: int) -> tuple:
    """Decode GatherMate2 packed coord to (x, y) zone-relative floats."""
    x = (coord // 1000000) / 10000
    y = ((coord % 1000000) // 100) / 10000
    return x, y


def extract_zones(filepath: str, zone_ids: list) -> dict:
    """Parse a GatherMate2 data file and extract specified zones."""
    print(f"  Reading {filepath}...")
    with open(filepath, 'r', encoding='utf-8', errors='replace') as f:
        content = f.read()

    result = {}
    for zone_id in zone_ids:
        nodes = parse_zone_block(content, zone_id)
        if nodes:
            result[zone_id] = nodes
            print(f"    Zone {zone_id} ({ALL_ZONES.get(zone_id, '?')}): {len(nodes)} nodes")
        else:
            print(f"    Zone {zone_id} ({ALL_ZONES.get(zone_id, '?')}): NOT FOUND")

    return result


def write_lua(herb_data: dict, mine_data: dict, outpath: str):
    """Write the self-contained QuestHUD_NodeData.lua file."""
    total_herb = sum(len(v) for v in herb_data.values())
    total_mine = sum(len(v) for v in mine_data.values())

    lines = []
    lines.append("-- QuestHUD_NodeData.lua")
    lines.append("-- Auto-generated by extract_nodes.py")
    lines.append(f"-- Generated: {datetime.now(tz=timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
    lines.append(f"-- Source: GatherMate2_Data community database (Wowhead data dump)")
    lines.append(f"-- Zones: Midnight (2393,2395,2405,2413,2437) + Arator's Journey (14,25,27)")
    lines.append(f"-- Herb nodes: {total_herb:,}  |  Mine nodes: {total_mine:,}")
    lines.append("--")
    lines.append("-- Coord format: floor(x*10000+0.5)*1000000 + floor(y*10000+0.5)*100")
    lines.append("-- Decode: x = floor(coord/1000000)/10000, y = floor(coord%1000000/100)/10000")
    lines.append("-- Values are zone-relative 0-1 fractions (same as HereBeDragons).")
    lines.append("--")
    lines.append("-- DO NOT EDIT MANUALLY. Re-run extract_nodes.py to regenerate.")
    lines.append("")

    # Node name lookup tables
    lines.append("-- ── Node ID → Name lookup ─────────────────────────────────────────────────")
    lines.append("QuestHUD_HerbNodeNames = {")
    for nid, name in sorted(HERB_NODE_NAMES.items()):
        lines.append(f"    [{nid}] = \"{name}\",")
    lines.append("}")
    lines.append("")
    lines.append("QuestHUD_MineNodeNames = {")
    for nid, name in sorted(MINE_NODE_NAMES.items()):
        lines.append(f"    [{nid}] = \"{name}\",")
    lines.append("}")
    lines.append("")

    # Midnight zone name lookup
    lines.append("-- ── Zone ID → Name lookup ─────────────────────────────────────────────────")
    lines.append("QuestHUD_ZoneNames = {")
    for zid, name in sorted(ALL_ZONES.items()):
        lines.append(f"    [{zid}] = \"{name}\",")
    lines.append("}")
    lines.append("")

    # Herb data
    lines.append("-- ── Herbalism node database ───────────────────────────────────────────────")
    lines.append("QuestHUD_BundledHerbDB = {")
    for zone_id in sorted(herb_data.keys()):
        nodes = herb_data[zone_id]
        zone_name = ALL_ZONES.get(zone_id, str(zone_id))
        lines.append(f"    [{zone_id}] = {{  -- {zone_name} ({len(nodes)} nodes)")
        for coord, node_id in sorted(nodes.items()):
            node_name = HERB_NODE_NAMES.get(node_id, f"Unknown({node_id})")
            lines.append(f"        [{coord}] = {node_id},  -- {node_name}")
        lines.append("    },")
    lines.append("}")
    lines.append("")

    # Mine data
    lines.append("-- ── Mining node database ─────────────────────────────────────────────────")
    lines.append("QuestHUD_BundledMineDB = {")
    for zone_id in sorted(mine_data.keys()):
        nodes = mine_data[zone_id]
        zone_name = ALL_ZONES.get(zone_id, str(zone_id))
        lines.append(f"    [{zone_id}] = {{  -- {zone_name} ({len(nodes)} nodes)")
        for coord, node_id in sorted(nodes.items()):
            node_name = MINE_NODE_NAMES.get(node_id, f"Unknown({node_id})")
            lines.append(f"        [{coord}] = {node_id},  -- {node_name}")
        lines.append("    },")
    lines.append("}")
    lines.append("")

    output = '\n'.join(lines)
    with open(outpath, 'w', encoding='utf-8', errors='replace') as f:
        f.write(output)

    size_kb = len(output.encode('utf-8')) / 1024
    print(f"\n  Written: {outpath}")
    print(f"  Size:    {size_kb:.1f} KB")
    print(f"  Nodes:   {total_herb:,} herb + {total_mine:,} mine = {total_herb+total_mine:,} total")


def main():
    parser = argparse.ArgumentParser(description="Extract QuestHUD node data from GatherMate2_Data")
    parser.add_argument('--herb', required=True, help='Path to HerbalismData.lua')
    parser.add_argument('--mine', required=True, help='Path to MiningData.lua')
    parser.add_argument('--out',  required=True, help='Output path for QuestHUD_NodeData.lua')
    args = parser.parse_args()

    zone_ids = list(ALL_ZONES.keys())

    print("\nExtracting herbalism nodes...")
    herb_data = extract_zones(args.herb, zone_ids)

    print("\nExtracting mining nodes...")
    mine_data = extract_zones(args.mine, zone_ids)

    print("\nWriting QuestHUD_NodeData.lua...")
    write_lua(herb_data, mine_data, args.out)

    print("\nDone. Add QuestHUD_NodeData.lua to your QuestHUD.toc load order")
    print("before QuestHUD_Gathering.lua.\n")


if __name__ == '__main__':
    main()
