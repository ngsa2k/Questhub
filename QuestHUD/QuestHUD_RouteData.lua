-- Source notes:
--   Quest names and quest types are prefilled from Wowhead's Midnight quest
--   listings and the Midnight expansion overview. IDs and objective coordinates
--   still need in-game verification where Blizzard/Wowhead have not exposed
--   stable quest IDs yet.
--
-- Catalog schema:
--   key         = stable internal key
--   id          = quest ID when confirmed, 0 when still unknown
--   name        = quest title shown to the player
--   type        = "campaign" | "side" | "firstcraft"
--   zone        = display zone name
--   hub         = display hub name
--   mapID       = zone map ID used by the arrow/info panel
--   x, y        = approximate zone-relative coordinates for the hub/objective
--   level       = intended quest level
--   xp          = approximate XP reward from Wowhead where visible, else 0
--   priority    = lower is preferred inside the same hub/chain
--   chain       = logical quest chain identifier
--   sequence    = position inside the logical chain
--   prereqs     = optional list of quest keys that must be considered done first

